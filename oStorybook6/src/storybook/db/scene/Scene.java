	/**
	 * get strands list in HTML beautify
	 *
	 * @return
	 */
	public String getStrandsHtml() {
		StringBuilder b = new StringBuilder(Html.HTML_B);
		b.append(Html.BODY_B);
		b.append("<table border=\"0\" cellpadding=\"0\" cellspacing=\"1\">");
		for (Strand s : strands) {
			b.append(Html.TR_B);
			b.append(Html.intoTD("█", "color=\"" + ColorUtil.getHTML(s.getJColor()) + "\""));
			b.append(Html.intoTD("&nbsp;"));
			b.append(Html.intoTD(s.getName()));
			b.append(Html.TR_E);
		}
		b.append(Html.TABLE_E);
		b.append(Html.BODY_E);
		b.append(Html.HTML_E);
		return b.toString();
	}

	/**
	 * get the identification like PpCccSnnn where p is the Part ID, cc is the Chapter ID and nnn is
	 * the Scene ID
	 *
	 * @return
	 */
	public String getIdent() {
		StringBuilder ident = new StringBuilder();
		if (hasChapter()) {
			ident.append(getChapter().getIdent());
		} else {
			ident.append("P0C00");
		}
		ident.append(String.format("S%03d", getId()));
		return ident.toString();
	}

	/**
	 * get a HTML file name for the scene
	 *
	 * @param scene
	 * @param bookTitle: empty seems it is a unique HTMLfile
	 * @return
	 */
	public static String getFilename(Scene scene, String bookTitle) {
		if (bookTitle.isEmpty()) {
			return "";
		}
		return String.format("%s-%s.html", bookTitle, scene.getIdent());
	}

