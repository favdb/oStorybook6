	@Override
	public String toDetail(Integer detailed) {
		//LOG.trace(TT+".toDetail(detailed=" + (detailed ? "true" : "false") + ")");
		StringBuilder b = new StringBuilder();
		String str;
		b.append(super.toDetailHeader(detailed));
		b.append(getInfo(2, DATA.NUMBER, getSceneno()));
		if (getStatus() > 0 || detailed > 0) {
			b.append(getInfo(detailed, DATA.STATUS, Status.getHtmlValue(getStatus())));
		}
		if (getIntensity().get() > 1 || detailed > 0) {
			IntensityPanel vi = new IntensityPanel(getIntensity().get());
			b.append(getInfo(detailed, DATA.INTENSITY, vi.getHtmlValue()));
		}
		b.append(getInfo(2, DATA.CHAPTER, getChapter()));
		if (getStrand() != null) {
			b.append(getInfo(detailed, DATA.STRAND, getClean(getStrand()) + " " + getStrand().getHTMLColor()));
		} else {
			b.append(getInfo(detailed, DATA.STRAND, I18N.getMsg("empty")));
		}
		b.append(getInfo(detailed, DATA.INFORMATIVE, getInformative()));
		b.append(getInfo(detailed, DATA.DATE, getClean(getScenets())));
		str = (getDuration().isEmpty() ? "" : getDurationToText());
		if (!str.isEmpty() || detailed > 1) {
			b.append(getInfo(detailed, DATA.DURATION, str));
		}
		if (getNarrator() != null || detailed > 1) {
			b.append(getInfo(detailed, DATA.SCENE_NARRATOR, getNarrator()));
		}
		if (App.getAssistant().isExists("scene")
				&& (!getScenariostage().isEmpty() || detailed > 1)) {
			b.append(getInfo(detailed, DATA.SCENARIO_STAGE, getScenariostage()));
		}
		//scenario
		if (!getScenario_pitch().isEmpty() || detailed > 1) {
			StringBuilder bx = new StringBuilder();
			bx.append(Html.TABLE_B).append(Html.TR_B);
			bx.append(getInfo(detailed, DATA.SCENARIO_PITCH, getScenario_pitch()));
			bx.append(getInfo(detailed, DATA.SCENARIO_LOC, getScenario_locTxt()));
			bx.append(getInfo(detailed, DATA.SCENARIO_MOMENT, getScenario_momentTxt()));
			bx.append(getInfo(detailed, DATA.SCENARIO_START, getScenario_startTxt()));
			bx.append(getInfo(detailed, DATA.SCENARIO_END, getScenario_endTxt()));
			bx.append(Html.TR_E).append(Html.TABLE_E);
			b.append(getInfo(detailed, "scenario", bx.toString()));
		}
		if (!getPersons().isEmpty() || detailed > 1) {
			b.append(getInfo(detailed, DATA.PERSONS, getPersonList()));
		}
		if (!getItems().isEmpty() || detailed > 1) {
			b.append(getInfo(detailed, DATA.ITEMS, getItemList()));
		}
		if (!getLocations().isEmpty() || detailed > 1) {
			b.append(getInfo(detailed, DATA.LOCATIONS, getLocationList()));
		}
		if (!getPlots().isEmpty() || detailed > 1) {
			b.append(getInfo(detailed, DATA.PLOTS, getPlotsList()));
		}
		if (!getStrands().isEmpty() || detailed > 1) {
			b.append(getInfo(detailed, DATA.STRANDS, getStrandsList()));
		}
		if (getRelativesceneid() > -1L) {
			SbDuration dx = new SbDuration(getRelativetime());
			str = getClean(getRelativesceneid()) + " ";
			if (!dx.toText().isEmpty()) {
				str = str + Html.intoB(I18N.getMsg("scene.relativetime")) + " "
						+ dx.toText(I18N.getMsg("duration.initiales"));
			}
		}
		b.append(getInfo(detailed, "scene.relative", str));
		//xeditor
		b.append(getInfo(detailed, "file", getOdf()));
		if (getSummary().contains(Html.P_E)) {
			b.append(getInfo(detailed, DATA.SCENE_SUMMARY, getSummary()));
		} else {
			b.append(getInfo(detailed, DATA.SCENE_SUMMARY, Markdown.toHtml(getSummary())));
		}
		b.append(super.toDetailFooter(detailed));
		return (b.toString());
	}

