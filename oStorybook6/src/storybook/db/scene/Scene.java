		StringBuilder b = new StringBuilder();
		b.append("<scene ");
		b.append(xmlCommon());
		b.append(XmlUtil.setAttribute(8, XK.NUMBER, getSceneno()));
		b.append(XmlUtil.setAttribute(0, XK.STATUS, getStatus()));
		b.append(XmlUtil.setAttribute(0, XK.INTENSITY, getIntensity().get()));
