		p.setSceneno(XmlUtil.getInteger(node, XK.NUMBER));
		String ts = XmlUtil.getString(node, XK.DATE);
		if (!ts.isEmpty()) {
			p.setScenets(Timestamp.valueOf(ts));
		}
		p.setInformative(getBoolean(node, XK.INFORMATIVE));
		p.setChapterId(getLong(node, XK.CHAPTER));
		p.setStrandId(getLong(node, XK.STRAND));
		p.setStatus(getInteger(node, XK.STATUS));
		p.setIntensity(getInteger(node, XK.INTENSITY));
		p.setDuration(getString(node, XK.DURATION));
		p.setRelativesceneid(getLong(node, XK.RELATIVESCENE));
		p.setRelativetime(getString(node, XK.RELATIVETIME));
		p.setScenario_pitch(getString(node, XK.PITCH));
		p.setScenario_loc(getInteger(node, XK.LOC));
		p.setScenario_moment(getInteger(node, XK.MOMENT));
		p.setScenario_start(getInteger(node, XK.START));
		p.setScenario_end(getInteger(node, XK.END));
		p.setOdf(getString(node, XK.FILE));
		p.setItemsId(getLongList(node, XK.ITEMS));
		p.setLocationsId(getLongList(node, XK.LOCATIONS));
		p.setPersonsId(getLongList(node, XK.PERSONS));
		p.setPlotsId(getLongList(node, XK.PLOTS));
		p.setStrandsId(getLongList(node, XK.STRANDS));
