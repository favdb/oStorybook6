		b.append(XmlUtil.setAttribute(0, XK.NARRATOR, getNarrator()));
		String x = getScenario_stage().toString() + getScenario_pitch() + getScenario_loc().toString()
				+ getScenario_moment() + getScenario_end().toString();
		x = x.replace("0", "");
		if (!x.isEmpty()) {
			b.append(XmlUtil.setAttribute(8, XK.STAGE, getScenario_stage()));
			b.append(XmlUtil.setAttribute(0, XK.PITCH, getScenario_pitch()));
			b.append(XmlUtil.setAttribute(0, XK.LOC, getScenario_loc()));
			b.append(XmlUtil.setAttribute(0, XK.MOMENT, getScenario_moment()));
			b.append(XmlUtil.setAttribute(0, XK.START, getScenario_start()));
			b.append(XmlUtil.setAttribute(0, XK.END, getScenario_end()));
		}
		b.append(XmlUtil.setAttribute(8, XK.PERSONS, EntityUtil.getIds(persons)));
		b.append(XmlUtil.setAttribute(8, XK.ITEMS, EntityUtil.getIds(items)));
		b.append(XmlUtil.setAttribute(8, XK.LOCATIONS, EntityUtil.getIds(locations)));
		b.append(XmlUtil.setAttribute(8, XK.STRANDS, EntityUtil.getIds(strands)));
		b.append(XmlUtil.setAttribute(8, XK.PLOTS, EntityUtil.getIds(plots)));
